#!/usr/bin/env python3
"""Export editable glyph grids as a compact Rust row-mask table.

The output is source code rather than a private binary format, so consumers
can `include!` it and review exactly what is embedded.

Usage: exportrows.py FONT_DIR [-o OUTPUT.rs]
"""
import sys
from pathlib import Path

from genfiglet import glyph_codepoint
from render import glyph_stem, grid_files, load_grid


def main(argv):
    args = list(argv)
    output = None
    if "-o" in args:
        index = args.index("-o")
        output = Path(args[index + 1])
        del args[index:index + 2]
    if len(args) != 1:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    entries = []
    for path in grid_files(Path(args[0])):
        codepoint = glyph_codepoint(glyph_stem(path))
        if codepoint is None:
            continue
        rows, width = load_grid(path, (1, 1))
        if width > 8 or len(rows) > 8:
            raise ValueError(f"{path}: Rust row export supports at most 8×8 grids")
        masks = [sum((cell not in " .") << (width - 1 - x) for x, cell in enumerate(row)) for row in rows]
        masks += [0] * (8 - len(masks))
        entries.append((codepoint, masks))
    lines = [
        "// Generated by sn8kfonts/tools/exportrows.py; edit the glyph grids, not this file.",
        "pub(crate) fn font_pixels(ch: char) -> Option<[u8; 8]> {",
        "    match ch {",
    ]
    for codepoint, rows in entries:
        values = ", ".join(f"0b{row:04b}" for row in rows)
        lines.append(f"        '\\u{{{codepoint:x}}}' => Some([{values}]),")
    lines.extend(["        _ => None,", "    }", "}", ""])
    text = "\n".join(lines)
    if output:
        output.write_text(text)
        print(f"{output}: {len(entries)} glyphs")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
