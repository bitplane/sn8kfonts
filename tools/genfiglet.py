#!/usr/bin/env python3
"""Generate a TOIlet .tlf font from a directory of glyph grid .txt files.

Glyph filenames: either a single character ("S.txt") or a codepoint with an
optional mnemonic ("0053_S.txt" — use this form for letters, so upper/lower
case can't collide on case-insensitive filesystems).

All glyphs are normalized to the tallest glyph's height (padded at the
bottom). Characters 32-126 that have no grid file are emitted as one-cell
blanks so any FIGlet parser accepts the font.

Metrics are baked into the glyphs so a standard (cell-level, full-width)
FIGlet/TOIlet engine spaces the font sensibly: every drawn glyph gets --gap
trailing empty subpixel columns, and the space character is --space + --gap
subpixels wide. A block-aware engine can decode the cells back to subpixel
bitmaps and kern properly; the "kern:" comment line in the header declares
which mode the font wants (auto = per-row subpixel kerning, fixed = advance
by container width, i.e. exactly what a standard engine does).

Header comment directives a block-aware engine may honour (standard engines
see plain comments): "kern: auto|fixed", "gap: N" (subpixels of daylight
auto-kern keeps between letters), "shade: gradient" (vertical shading hint),
"linegap: N" (subpixel rows between stacked lines).

--caps draws a-z with the A-Z glyphs, for an all-capitals font.

A CREDITS file in FONT_DIR replaces the WTFPL comment line with its lines.

Usage: genfiglet.py FONT_DIR [-o OUT.tlf] [--encoding sextant|halfblock|octant|text]
                    [--gap N] [--space N] [--kern auto|fixed]
                    [--shade gradient] [--linegap N] [--caps]
"""
import sys
from pathlib import Path

from render import ENCODINGS, empty, glyph_stem, grid_files, load_grid, render

END = "@"


def hardblank(glyphs):
    """A hardblank the glyphs don't draw: "$" unless a text font has a "$"."""
    used = {c for rows in glyphs for row in rows for c in row}
    return next(c for c in "$~`^\x7f" if c not in used)


def glyph_codepoint(stem):
    if len(stem) == 1:
        return ord(stem)
    head = stem.split("_", 1)[0]
    if 4 <= len(head) <= 6:
        try:
            return int(head, 16)
        except ValueError:
            pass
    return None


def flag(args, name, default, cast=str):
    if name in args:
        i = args.index(name)
        value = cast(args[i + 1])
        del args[i : i + 2]
        return value
    return default


def main(argv):
    args = list(argv)
    out = flag(args, "-o", None, Path)
    encoding = flag(args, "--encoding", "sextant")
    gap = flag(args, "--gap", 1, int)
    space = flag(args, "--space", 2, int)
    kern = flag(args, "--kern", "auto")
    shade = flag(args, "--shade", None)
    linegap = flag(args, "--linegap", 0, int)
    caps = "--caps" in args
    if caps:
        args.remove("--caps")
    if len(args) != 1 or encoding not in ENCODINGS or kern not in ("auto", "fixed"):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    font_dir = Path(args[0])
    name = font_dir.name
    out = out or Path(f"{name}.tlf")
    cw, ch, _ = ENCODINGS[encoding]
    pad = empty(encoding)

    # Grids stay at subpixel resolution until the very end: bake the gap,
    # normalize heights, THEN encode — so cell padding never eats a metric.
    grids = {}
    for f in grid_files(font_dir):
        cp = glyph_codepoint(glyph_stem(f))
        if cp is None:
            print(f"skipping {f.name}: name is not a char or codepoint", file=sys.stderr)
            continue
        rows, width = load_grid(f, (1, 1))
        grids[cp] = [r + pad * gap for r in rows]
    if caps:
        for cp in range(ord("a"), ord("z") + 1):
            if cp - 32 in grids:
                grids[cp] = grids[cp - 32]
    if 32 not in grids:
        grids[32] = [pad * (space + gap)]

    subpx_height = max((len(g) for g in grids.values()), default=ch)
    subpx_height += -subpx_height % ch

    def encode(grid):
        width = max(len(r) for r in grid)
        width += -width % cw
        rows = [r.ljust(width, pad) for r in grid]
        rows += [pad * width] * (subpx_height - len(rows))
        return render(rows, width, encoding).split("\n")

    height = subpx_height // ch
    blank = [" "] * height

    lines = []
    max_len = 0
    codepoints = sorted(set(range(32, 127)) | set(grids))
    body = {}
    for cp in codepoints:
        g = encode(grids[cp]) if cp in grids else blank
        body[cp] = g
        # max_length spans the longest line INCLUDING endmarks, and each
        # glyph's final row carries a double endmark; toilet truncates
        # glyph lines past this, so undercounting garbles every glyph.
        max_len = max(max_len, max(len(r) for r in g) + 2)

    comments = [
        f"{name} - generated by sn8kfonts/tools/genfiglet.py",
        f"kern: {kern}",
        f"gap: {gap}",
    ]
    if shade:
        comments.append(f"shade: {shade}")
    if linegap:
        comments.append(f"linegap: {linegap}")
    # A font drawn from someone else's says so in its own words.
    credits = font_dir / "CREDITS"
    comments.extend(credits.read_text().splitlines() if credits.exists() else ["WTFPL"])
    # required glyph order per the FIGfont spec: 32-126, then the seven
    # Deutsch characters untagged (toilet enforces this, figlet forgives),
    # then anything else as codetagged sections
    deutsch = [196, 214, 220, 228, 246, 252, 223]
    lines.append(f"tlf2a{hardblank(body.values())} {height} {height} {max_len} -1 {len(comments)}")
    lines.extend(comments)

    def emit(cp):
        g = body.get(cp, blank)
        for i, row in enumerate(g):
            lines.append(row + (END * 2 if i == height - 1 else END))

    for cp in range(32, 127):
        emit(cp)
    for cp in deutsch:
        emit(cp)
    for cp in codepoints:
        if cp < 127 or cp in deutsch:
            continue
        lines.append(f"0x{cp:04X}")
        emit(cp)

    out.write_text("\n".join(lines) + "\n")
    named = sum(1 for cp in grids if cp != 32)
    blanks = 94 - len([c for c in grids if 32 < c < 127])
    print(f"{out}: {encoding}, kern {kern}, height {height}, {named} drawn glyphs, {blanks} ASCII blanks")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent))
    sys.exit(main(sys.argv[1:]))
